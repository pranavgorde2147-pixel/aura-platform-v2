"""Brain memory ORM model for persistent personal memories.

Memories are explicitly labelled so that retrieved *facts* are never confused
with AI-generated *interpretations*. Persisting a memory is an explicit action;
conversations are not saved automatically.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from enum import Enum
from typing import TYPE_CHECKING

from sqlalchemy import DateTime, Enum as SQLAlchemyEnum, ForeignKey, Integer, String, Text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import BaseModel

if TYPE_CHECKING:
    from app.models.ai_identity import AIIdentity


class MemoryKind(str, Enum):
    """The provenance category of a memory."""

    FACT = "fact"  # supplied by the user or an application
    INTERPRETATION = "interpretation"  # generated by the AI
    EVENT = "event"  # timeline-style activity record


class MemorySource(str, Enum):
    """Who created the memory."""

    USER = "user"
    BRAIN = "brain"
    APP = "app"


class BrainMemory(BaseModel):
    """A persistent memory belonging to an AI identity's Personal Brain."""

    __tablename__ = "brain_memories"

    ai_identity_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("ai_identities.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    kind: Mapped[MemoryKind] = mapped_column(
        SQLAlchemyEnum(MemoryKind, native_enum=False),
        default=MemoryKind.FACT,
        nullable=False,
        index=True,
    )
    source: Mapped[MemorySource] = mapped_column(
        SQLAlchemyEnum(MemorySource, native_enum=False),
        default=MemorySource.USER,
        nullable=False,
        index=True,
    )
    content: Mapped[str] = mapped_column(Text, nullable=False)
    summary: Mapped[str | None] = mapped_column(String(512), nullable=True)
    source_app: Mapped[str | None] = mapped_column(String(128), nullable=True, index=True)
    importance: Mapped[int] = mapped_column(Integer, default=0, nullable=False, index=True)
    embedding_status: Mapped[str] = mapped_column(String(32), default="pending", nullable=False, index=True)
    # Retention: ``None`` means "keep until the user deletes it". A concrete
    # timestamp is set when the configured retention policy applies an expiry.
    retention_policy: Mapped[str] = mapped_column(
        String(64), default="default", nullable=False, index=True
    )
    expires_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True, index=True
    )

    ai_identity: Mapped["AIIdentity"] = relationship(lazy="selectin")
